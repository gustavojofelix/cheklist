// Build-time environment for Netlify (one codebase, several sites):
//   SUPABASE_URL, SUPABASE_ANON_KEY  → src/environments/environment.prod.ts (git-ignored)
//   APP_ENV = production | staging | dev (default dev)
// Without the variables the build falls back to the committed dev project (environment.ts),
// EXCEPT when APP_ENV=production, where missing variables fail the build.
import { readFileSync, writeFileSync } from 'node:fs';

const env = process.env.APP_ENV ?? 'dev';
let url = process.env.SUPABASE_URL;
let key = process.env.SUPABASE_ANON_KEY;

if (!url || !key) {
  if (env === 'production') {
    console.error('APP_ENV=production requires SUPABASE_URL and SUPABASE_ANON_KEY');
    process.exit(1);
  }
  const dev = readFileSync('src/environments/environment.ts', 'utf8');
  url = dev.match(/supabaseUrl:\s*'([^']+)'/)[1];
  key = dev.match(/supabaseKey:\s*\n?\s*'([^']+)'/)[1];
  console.warn(`build-env: SUPABASE_URL/ANON_KEY not set — using the dev project (${url})`);
}
if (!/^https:\/\/[a-z0-9-]+\.supabase\.co$/.test(url) && !/^https:\/\/[a-z0-9.-]+$/.test(url)) {
  console.error(`build-env: unexpected SUPABASE_URL ${url}`);
  process.exit(1);
}
if (key.startsWith('sb_secret') || /"role":"service_role"/.test(Buffer.from(key.split('.')[1] ?? '', 'base64').toString())) {
  console.error('build-env: refusing to bundle a SECRET/service-role key into the browser');
  process.exit(1);
}

writeFileSync('src/environments/environment.prod.ts',
  `// Generated by scripts/build-env.mjs — do not edit or commit.\n` +
  `export const environment = { production: ${env === 'production'}, appEnv: '${env}', supabaseUrl: '${url}', supabaseKey: '${key}' };\n`);
writeFileSync('.build-env.json', JSON.stringify({ env, url }));
console.log(`build-env: ${env} → ${url}`);
