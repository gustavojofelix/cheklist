// report-generate: compliance report for selected checklist items, as PDF and Word (DOCX).
// Reads data AS THE CALLER (RLS), stores files in the private `reports` bucket,
// records the report + an audit entry, and returns short-lived signed URLs.
import { PDFDocument, PDFFont, rgb, StandardFonts } from 'npm:pdf-lib@1.17.1';
import {
  AlignmentType, Document, HeadingLevel, Packer, Paragraph, Table, TableCell, TableRow, TextRun, WidthType,
} from 'npm:docx@9.15.3';
import { adminClient, clientIp, corsHeaders, fail, json, requireUser, setOrigin } from '../_shared/http.ts';

type Lang = 'pt' | 'en';
interface Item {
  id: string; parent_id: string | null; is_category: boolean; catalog_code: string | null; title: string;
  translations: { en?: { title?: string } }; answer: string | null; answer_kind: string; due_date: string | null; has_validity: boolean;
  is_applicable: boolean; compliance_state: 'regular' | 'atencao' | 'critico'; sort_order: number; document_count: number;
}

const L = {
  pt: { title: 'Relatório de conformidade', entity: 'Entidade', generated: 'Gerado em', by: 'por', items: 'Itens',
        code: 'ID', item: 'Item', answer: 'Descritivo', validity: 'Validade', state: 'Estado', docs: 'Doc.',
        regular: 'Regular', atencao: 'Atenção', critico: 'Crítico', na: 'Não aplicável', page: 'Página',
        summary: 'Resumo', disclaimer: 'Documento gerado automaticamente pelo Checklist Legal. Não constitui aconselhamento jurídico.' },
  en: { title: 'Compliance report', entity: 'Entity', generated: 'Generated on', by: 'by', items: 'Items',
        code: 'ID', item: 'Item', answer: 'Description', validity: 'Validity', state: 'State', docs: 'Docs',
        regular: 'Compliant', atencao: 'Attention', critico: 'Critical', na: 'Not applicable', page: 'Page',
        summary: 'Summary', disclaimer: 'Automatically generated by Checklist Legal. Not legal advice.' },
};

Deno.serve(async (req) => {
  setOrigin(req);
  if (req.method === 'OPTIONS') return new Response('ok', { headers: corsHeaders() });
  const auth = await requireUser(req);
  if (auth instanceof Response) return auth;
  const { user, db } = auth;

  const body = await req.json().catch(() => ({}));
  const checklistId = body.checklist_id as string;
  const itemIds = (body.item_ids ?? []) as string[];
  const lang: Lang = body.lang === 'en' ? 'en' : 'pt';
  if (!checklistId || !Array.isArray(itemIds) || !itemIds.length || itemIds.length > 500) return fail('select_at_least_one_item');

  // RLS: the caller only gets rows they may read.
  const { data: checklist } = await db.from('checklists').select('id, organization_id, title').eq('id', checklistId).maybeSingle();
  if (!checklist) return fail('not_found', 404);
  const [{ data: org }, { data: rows }, { data: profile }] = await Promise.all([
    db.from('organizations').select('name, tax_id').eq('id', checklist.organization_id).single(),
    db.from('checklist_items_state').select('id, parent_id, is_category, catalog_code, title, translations, answer, answer_kind, due_date, has_validity, is_applicable, compliance_state, sort_order, document_count')
      .eq('checklist_id', checklistId).order('sort_order'),
    db.from('profiles').select('full_name').eq('id', user.id).single(),
  ]);
  const all = (rows ?? []) as Item[];
  const wanted = new Set(itemIds);
  const cats = all.filter((i) => i.is_category && !i.parent_id);
  const groups = cats.map((c) => ({ cat: c, items: all.filter((i) => i.parent_id === c.id && wanted.has(i.id)) }))
    .filter((g) => g.items.length);
  const selected = groups.flatMap((g) => g.items);
  if (!selected.length) return fail('select_at_least_one_item');

  // Answers bound to the sector list hold the code; print its label.
  const { data: sectors } = await db.from('reference_lists').select('value, label').eq('list_key', 'sector');
  const sectorLabel = new Map((sectors ?? []).map((s: { value: string; label: { pt: string; en?: string } }) =>
    [s.value, lang === 'en' ? s.label.en ?? s.label.pt : s.label.pt]));
  for (const it of selected) {
    if (it.answer_kind === 'sector' && it.answer) it.answer = sectorLabel.get(it.answer) ?? it.answer;
  }

  const t = L[lang];
  const tr = (i: Item) => (lang === 'en' ? i.translations?.en?.title ?? i.title : i.title);
  const stateLabel = (i: Item) => (i.is_applicable ? t[i.compliance_state] : t.na);
  const date = (d: string | null) => (d ? d.split('-').reverse().join('/') : '—');
  const now = new Date();
  const genLine = `${t.generated} ${now.toISOString().slice(0, 16).replace('T', ' ')} UTC ${t.by} ${profile?.full_name ?? ''}`;
  const counts = { regular: 0, atencao: 0, critico: 0 };
  selected.forEach((i) => { if (i.is_applicable) counts[i.compliance_state]++; });

  const pdf = await buildPdf({ t, org: org!, groups, tr, stateLabel, date, genLine, counts });
  const docx = await buildDocx({ t, org: org!, groups, tr, stateLabel, date, genLine, counts });

  const admin = adminClient();
  const reportId = crypto.randomUUID();
  const base = `${checklist.organization_id}/${reportId}`;
  const pdfPath = `${base}/relatorio.pdf`;
  const docxPath = `${base}/relatorio.docx`;
  const up1 = await admin.storage.from('reports').upload(pdfPath, pdf, { contentType: 'application/pdf' });
  const up2 = await admin.storage.from('reports').upload(docxPath, docx, {
    contentType: 'application/vnd.openxmlformats-officedocument.wordprocessingml.document' });
  if (up1.error || up2.error) return fail('storage_error', 500);

  await admin.from('reports').insert({ id: reportId, organization_id: checklist.organization_id, checklist_id: checklistId,
    item_ids: selected.map((i) => i.id), pdf_path: pdfPath, docx_path: docxPath, created_by: user.id });
  await admin.rpc('log_event', { p_event: 'report.generate', p_org: checklist.organization_id, p_table: 'reports',
    p_record: reportId, p_title: `${selected.length} ${t.items.toLowerCase()}`, p_actor: user.id,
    p_ip: clientIp(req), p_user_agent: req.headers.get('user-agent') });

  const stamp = now.toISOString().slice(0, 10);
  const [s1, s2] = await Promise.all([
    admin.storage.from('reports').createSignedUrl(pdfPath, 600, { download: `relatorio-${stamp}.pdf` }),
    admin.storage.from('reports').createSignedUrl(docxPath, 600, { download: `relatorio-${stamp}.docx` }),
  ]);
  const inline = await admin.storage.from('reports').createSignedUrl(pdfPath, 600);
  return json({ id: reportId, pdf_url: s1.data?.signedUrl, docx_url: s2.data?.signedUrl, preview_url: inline.data?.signedUrl });
});

// ------------------------------------------------------------------ PDF
interface Ctx {
  t: typeof L.pt; org: { name: string; tax_id: string | null }; groups: { cat: Item; items: Item[] }[];
  tr: (i: Item) => string; stateLabel: (i: Item) => string; date: (d: string | null) => string; genLine: string;
  counts: { regular: number; atencao: number; critico: number };
}

// Standard PDF fonts use WinAnsi: keep Latin-1 (accents are fine), replace the rest.
const safe = (s: string) => s.replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/[^\x09\x0A\x0D\x20-\x7E -ÿ—–•€]/g, '?');

function wrap(text: string, font: PDFFont, size: number, width: number): string[] {
  const out: string[] = [];
  for (const para of safe(text).split('\n')) {
    let line = '';
    for (const word of para.split(/\s+/)) {
      const test = line ? `${line} ${word}` : word;
      if (font.widthOfTextAtSize(test, size) <= width) line = test;
      else { if (line) out.push(line); line = word; }
    }
    out.push(line);
  }
  return out;
}

async function buildPdf(c: Ctx): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle(`${c.t.title} — ${c.org.name}`);
  doc.setProducer('Checklist Legal');
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const W = 595.28, H = 841.89, M = 40;
  const cols = [{ w: 55, k: 'code' }, { w: 150, k: 'item' }, { w: 175, k: 'answer' }, { w: 60, k: 'validity' }, { w: 75, k: 'state' }];
  const color = { regular: rgb(0.06, 0.6, 0.4), atencao: rgb(0.85, 0.55, 0.05), critico: rgb(0.86, 0.15, 0.15) };
  let page = doc.addPage([W, H]);
  let y = H - M;
  const pages = [page];

  const header = () => {
    page.drawText(safe('Checklist Legal'), { x: M, y: H - 28, size: 8, font: bold, color: rgb(0.11, 0.3, 0.85) });
    page.drawText(safe(c.org.name), { x: W - M - font.widthOfTextAtSize(safe(c.org.name), 8), y: H - 28, size: 8, font, color: rgb(0.4, 0.45, 0.5) });
  };
  const newPage = () => { page = doc.addPage([W, H]); pages.push(page); y = H - M - 10; header(); };
  const ensure = (h: number) => { if (y - h < M + 20) newPage(); };

  header();
  y -= 20;
  page.drawText(safe(c.t.title), { x: M, y, size: 18, font: bold }); y -= 22;
  page.drawText(safe(`${c.t.entity}: ${c.org.name}${c.org.tax_id ? ' · NUIT ' + c.org.tax_id : ''}`), { x: M, y, size: 10, font }); y -= 14;
  page.drawText(safe(c.genLine), { x: M, y, size: 8, font, color: rgb(0.45, 0.5, 0.55) }); y -= 22;

  // summary boxes
  const boxes: [string, number, ReturnType<typeof rgb>][] = [
    [c.t.regular, c.counts.regular, color.regular], [c.t.atencao, c.counts.atencao, color.atencao], [c.t.critico, c.counts.critico, color.critico]];
  boxes.forEach(([label, n, col], i) => {
    const x = M + i * 172;
    page.drawRectangle({ x, y: y - 36, width: 160, height: 40, borderColor: col, borderWidth: 1 });
    page.drawText(String(n), { x: x + 10, y: y - 22, size: 16, font: bold, color: col });
    page.drawText(safe(label), { x: x + 50, y: y - 18, size: 10, font });
  });
  y -= 56;

  const drawHead = () => {
    let x = M;
    page.drawRectangle({ x: M, y: y - 4, width: W - 2 * M, height: 16, color: rgb(0.95, 0.96, 0.98) });
    for (const col of cols) { page.drawText(safe((c.t as Record<string, string>)[col.k]), { x: x + 3, y, size: 8, font: bold }); x += col.w; }
    y -= 18;
  };

  for (const g of c.groups) {
    ensure(50);
    page.drawText(safe(c.tr(g.cat)), { x: M, y, size: 11, font: bold, color: rgb(0.11, 0.3, 0.85) }); y -= 16;
    drawHead();
    for (const it of g.items) {
      const cells = [it.catalog_code ?? '', c.tr(it), it.answer ?? '—', it.has_validity ? c.date(it.due_date) : '—', c.stateLabel(it)];
      const lines = cells.map((v, i) => wrap(v, font, 8, cols[i].w - 6));
      const h = Math.max(...lines.map((l) => l.length)) * 10 + 4;
      if (y - h < M + 20) { newPage(); drawHead(); }
      let x = M;
      lines.forEach((ls, i) => {
        const col = i === 4 && it.is_applicable ? color[it.compliance_state] : rgb(0.12, 0.16, 0.22);
        ls.forEach((ln, j) => page.drawText(ln, { x: x + 3, y: y - j * 10, size: 8, font: i === 4 ? bold : font, color: col }));
        x += cols[i].w;
      });
      y -= h;
      page.drawLine({ start: { x: M, y: y + 6 }, end: { x: W - M, y: y + 6 }, thickness: 0.3, color: rgb(0.88, 0.9, 0.92) });
    }
    y -= 10;
  }
  ensure(30);
  page.drawText(safe(c.t.disclaimer), { x: M, y: y - 10, size: 7, font, color: rgb(0.5, 0.55, 0.6) });
  pages.forEach((p, i) => p.drawText(safe(`${c.t.page} ${i + 1} / ${pages.length}`), { x: W - M - 50, y: 22, size: 7, font, color: rgb(0.5, 0.55, 0.6) }));
  return await doc.save();
}

// ------------------------------------------------------------------ DOCX
async function buildDocx(c: Ctx): Promise<Uint8Array> {
  const colour = { regular: '0F9960', atencao: 'D98C0D', critico: 'DB2626' };
  const cell = (text: string, opts: { bold?: boolean; color?: string; shade?: string; width: number }) =>
    new TableCell({
      width: { size: opts.width, type: WidthType.PERCENTAGE },
      shading: opts.shade ? { fill: opts.shade } : undefined,
      children: [new Paragraph({ children: [new TextRun({ text, bold: opts.bold, color: opts.color, size: 18 })] })],
    });
  const widths = [10, 28, 34, 13, 15];
  const children: (Paragraph | Table)[] = [
    new Paragraph({ heading: HeadingLevel.TITLE, children: [new TextRun(c.t.title)] }),
    new Paragraph({ children: [new TextRun({ text: `${c.t.entity}: `, bold: true }), new TextRun(`${c.org.name}${c.org.tax_id ? ' · NUIT ' + c.org.tax_id : ''}`)] }),
    new Paragraph({ children: [new TextRun({ text: c.genLine, color: '64748B', size: 16 })] }),
    new Paragraph({ heading: HeadingLevel.HEADING_2, children: [new TextRun(c.t.summary)] }),
    new Paragraph({ children: [
      new TextRun({ text: `${c.t.regular}: ${c.counts.regular}   `, color: colour.regular, bold: true }),
      new TextRun({ text: `${c.t.atencao}: ${c.counts.atencao}   `, color: colour.atencao, bold: true }),
      new TextRun({ text: `${c.t.critico}: ${c.counts.critico}`, color: colour.critico, bold: true })] }),
  ];
  for (const g of c.groups) {
    children.push(new Paragraph({ heading: HeadingLevel.HEADING_2, children: [new TextRun(c.tr(g.cat))] }));
    const head = new TableRow({ tableHeader: true, children: [c.t.code, c.t.item, c.t.answer, c.t.validity, c.t.state]
      .map((h, i) => cell(h, { bold: true, shade: 'F1F5F9', width: widths[i] })) });
    const rows = g.items.map((it) => new TableRow({ children: [
      cell(it.catalog_code ?? '', { width: widths[0] }), cell(c.tr(it), { width: widths[1] }),
      cell(it.answer ?? '—', { width: widths[2] }), cell(it.has_validity ? c.date(it.due_date) : '—', { width: widths[3] }),
      cell(c.stateLabel(it), { bold: true, color: it.is_applicable ? colour[it.compliance_state] : '64748B', width: widths[4] }),
    ] }));
    children.push(new Table({ width: { size: 100, type: WidthType.PERCENTAGE }, rows: [head, ...rows] }));
  }
  children.push(new Paragraph({ alignment: AlignmentType.LEFT, spacing: { before: 300 },
    children: [new TextRun({ text: c.t.disclaimer, size: 14, color: '64748B' })] }));
  const doc = new Document({ creator: 'Checklist Legal', title: c.t.title, sections: [{ children }] });
  return new Uint8Array(await Packer.toArrayBuffer(doc));
}
